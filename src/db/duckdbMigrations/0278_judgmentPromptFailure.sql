CREATE TABLE IF NOT EXISTS app.judgment_prompt_failure (
  article_id VARCHAR NOT NULL,
  prompt_id VARCHAR NOT NULL,
  model_id VARCHAR NOT NULL,
  use_title BOOLEAN NOT NULL,
  use_abstract BOOLEAN NOT NULL,
  use_fulltext BOOLEAN NOT NULL,
  use_fulltext_no_images BOOLEAN NOT NULL,
  use_metadata BOOLEAN NOT NULL,
  system_prompt_variant VARCHAR NOT NULL,
  full_text_strategy_id VARCHAR NOT NULL,
  project_id VARCHAR NOT NULL,
  judgment_job_id VARCHAR NOT NULL,
  queue_prompt_id VARCHAR NOT NULL,
  last_claim_id VARCHAR NOT NULL,
  failure_code VARCHAR NOT NULL,
  reason VARCHAR NOT NULL,
  provider_kind VARCHAR,
  model_name VARCHAR,
  attempt_count INTEGER NOT NULL,
  failure_count INTEGER NOT NULL DEFAULT 1,
  first_failed_at TIMESTAMPTZ NOT NULL,
  last_failed_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
  PRIMARY KEY (
    article_id,
    prompt_id,
    model_id,
    use_title,
    use_abstract,
    use_fulltext,
    use_fulltext_no_images,
    use_metadata,
    system_prompt_variant,
    full_text_strategy_id
  ),
  CHECK (length(trim(failure_code)) > 0),
  CHECK (length(trim(reason)) > 0),
  CHECK (attempt_count >= 0),
  CHECK (failure_count >= 1),
  CHECK (first_failed_at <= last_failed_at)
);
